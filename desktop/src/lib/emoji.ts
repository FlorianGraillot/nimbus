export function emojiSearch(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const all = EMOJI_CATEGORIES.flatMap((c) => c.emojis);
  return [...new Set(all)].filter((e) => e.includes(q)).slice(0, 48);
}
